const inv = (ch: string) => (...a: unknown[]) => ipcRenderer.invoke(ch, ...a)
function on<T extends unknown[]>(ch: string, cb: (...a: T) => void) {
  const l = (_e: unknown, ...a: unknown[]) => cb(...(a as T))
  ipcRenderer.on(ch, l)
  return () => {
    ipcRenderer.removeListener(ch, l)
  }
}

